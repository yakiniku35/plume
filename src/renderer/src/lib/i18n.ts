export const dictionaries: Record<Locale, Dict> = { en, 'zh-Hans': zhHans, 'zh-Hant': zhHant }

export function detectLocale(): Locale {
  const lang = navigator.language.toLowerCase()
  if (lang.startsWith('zh')) {
    return lang.includes('tw') || lang.includes('hk') || lang.includes('mo') || lang.includes('hant') ? 'zh-Hant' : 'zh-Hans'
  }
  return 'en'
}

export function intlTag(locale: Locale): string {
  return locale === 'en' ? 'en-US' : locale === 'zh-Hans' ? 'zh-CN' : 'zh-TW'
}

export type TKey = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict]

export interface I18n {
  locale: Locale
  dict: Dict
  t(key: TKey, vars?: Record<string, string | number>): string
}

export function makeI18n(locale: Locale): I18n {
  const dict = dictionaries[locale]
  return {
    locale,
    dict,
    t(key, vars) {
      let s = dict[key] as string
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
      return s
    }
  }
}

export const I18nContext = createContext<I18n>(makeI18n('en'))
export const useI18n = (): I18n => useContext(I18nContext)
